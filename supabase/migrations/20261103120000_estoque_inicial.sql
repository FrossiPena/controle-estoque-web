-- Controle de Estoque — fase 1 (alimentação dupla): espelho das planilhas Google no schema "estoque".
-- O schema NÃO é exposto pela Data API: só a Edge Function "espelho" (conexão direta, SUPABASE_DB_URL) acessa.
-- Cada tabela guarda a linha da planilha no id/linha_planilha, para os dois lados apontarem para a mesma linha.
-- Colunas *_norm / chave_c são geradas aqui (mesmas regras de normCod_, normCodigo_ e chaveCodigoC_ dos .gs),
-- assim o CSV importado pelo painel não precisa de pré-processamento.

create schema if not exists estoque;
revoke all on schema estoque from public, anon, authenticated;

-- inventario.gs normCodigo_: sem zeros à esquerda; vazio = "0"
-- consolidado.gs normCod_:   sem ".0" no fim e sem zeros à esquerda (deixa um caractere)
-- consolidado.gs chaveCodigoC_: "C 051.001-621.111 002" -> "C051001621111"

-- Aba Movimentacoes (A..N). id = linha da planilha.
create table estoque.movimentacoes (
  id bigint generated by default as identity primary key,
  campo1 text, campo2 text, loc text, rua text, andar text, gps text,
  datahora timestamptz, num_inv text,
  foto1 text, foto2 text, foto3 text, foto4 text,
  obs text, usuario text,
  campo1_norm text generated always as
    (coalesce(nullif(regexp_replace(btrim(coalesce(campo1, '')), '^0+', ''), ''), '0')) stored,
  campo2_norm text generated always as
    (coalesce(nullif(regexp_replace(btrim(coalesce(campo2, '')), '^0+', ''), ''), '0')) stored,
  apagado_em timestamptz, apagado_por text            -- "Deletar linha" (clear_lin) não apaga: marca
);
create index movimentacoes_campo1_idx on estoque.movimentacoes (campo1_norm, id desc);

-- Aba "MachineCards Consolidado" (A..M). id = linha da planilha. Colunas usadas pelo app: C, H, I, K, L, M.
create table estoque.machinecards (
  id bigint generated by default as identity primary key,
  col_a text, col_b text, col_c text, col_d text, col_e text, col_f text, col_g text,
  codigo9 text,          -- H
  descricao text,        -- I
  col_j text,
  id_individual text,    -- K
  codigo_c text,         -- L
  gt text,               -- M
  codigo9_norm text generated always as
    (regexp_replace(regexp_replace(btrim(coalesce(codigo9, '')), '\.0+$', ''), '^0+(?=.)', '')) stored,
  id_norm text generated always as
    (regexp_replace(regexp_replace(btrim(coalesce(id_individual, '')), '\.0+$', ''), '^0+(?=.)', '')) stored,
  chave_c text generated always as
    (coalesce(substring(regexp_replace(upper(coalesce(codigo_c, '')), '[^0-9A-Z]', '', 'g') from '^C[0-9]{12}'), '')) stored
);
create index machinecards_codigo9_idx on estoque.machinecards (codigo9_norm, id_norm);
create index machinecards_chave_c_idx on estoque.machinecards (chave_c);
create index machinecards_gt_idx on estoque.machinecards (lower(gt));

-- Aba AJUSTE (A..M), só acrescenta linhas. id = linha da aba.
create table estoque.ajustes (
  id bigint generated by default as identity primary key,
  datahora timestamptz, usuario text, gt text, modelo text,
  posicao text,          -- POSICAO (CODIGO C)
  descricao text,
  c9_antigo text, id_antigo text, c9_novo text, id_novo text,
  alerta text, obs text,
  codigo_c_novo text     -- M
);
create index ajustes_gt_idx on estoque.ajustes (lower(gt));
create index ajustes_novo_idx on estoque.ajustes (c9_novo, id_novo);

-- RELAÇÃO: aba "Gruas lista" (modelos para o app, coluna D a partir da linha 4)
create table estoque.gruas_lista (
  linha_planilha int primary key,
  modelo text not null
);

-- RELAÇÃO: aba "Validação" (TAG = GT na coluna C, Modelo na D, a partir da linha 4)
create table estoque.validacao (
  linha_planilha int primary key,
  gt text not null,
  modelo text
);

-- RELAÇÃO: uma linha por aba de modelo (a linha 2 tem "CÓDIGO LBR")
create table estoque.relacao_abas (
  aba text primary key,                 -- nome da aba, como na planilha
  linha1 jsonb not null default '[]',   -- linha 1 (configurador) guardada como estava
  cabecalho jsonb not null default '[]',-- linha 2
  colunas_compat int[] not null default '{}', -- colunas (1 = A) com título COMPATÍVEL n, na ordem
  lancas text[] not null default '{}'   -- títulos de comprimento de lança ("75m", "36,7m"…), na ordem
);

-- RELAÇÃO: linhas das abas de modelo, da linha 3 em diante (linha sem código = título de grupo)
create table estoque.relacao_itens (
  aba text not null references estoque.relacao_abas (aba) on update cascade on delete cascade,
  linha_planilha int not null,
  grupo text, descricao text, codigo_lbr text,
  compat1 text, compat2 text, compat3 text, compat4 text,
  peso numeric, comprimento text, gt text,
  qtd jsonb not null default '{}',      -- {"75m": 1, "70m": 2}
  extra jsonb not null default '{}',    -- demais colunas (preços etc.), pelo título da linha 2
  chave_c text generated always as
    (coalesce(substring(regexp_replace(upper(coalesce(codigo_lbr, '')), '[^0-9A-Z]', '', 'g') from '^C[0-9]{12}'), '')) stored,
  primary key (aba, linha_planilha)
);
create index relacao_itens_chave_c_idx on estoque.relacao_itens (chave_c);

-- Compatíveis gravados pelo app (substitui a nota que o Apps Script põe na célula)
create table estoque.relacao_compat_log (
  id bigint generated always as identity primary key,
  criado_em timestamptz not null default now(),
  usuario text, aba text, linha_planilha int, coluna text, codigo_c text, nota text
);

-- Toda chamada da função "espelho" (o que deu certo e o que não deu)
create table estoque.espelho_log (
  id bigint generated always as identity primary key,
  criado_em timestamptz not null default now(),
  usuario text, modo text, ok boolean not null, ref text, detalhe text
);
create index espelho_log_falhas_idx on estoque.espelho_log (criado_em desc) where not ok;

-- RLS ligada sem policies: anon/authenticated não leem nem gravam (além do schema não exposto)
alter table estoque.movimentacoes enable row level security;
alter table estoque.machinecards enable row level security;
alter table estoque.ajustes enable row level security;
alter table estoque.gruas_lista enable row level security;
alter table estoque.validacao enable row level security;
alter table estoque.relacao_abas enable row level security;
alter table estoque.relacao_itens enable row level security;
alter table estoque.relacao_compat_log enable row level security;
alter table estoque.espelho_log enable row level security;

-- Depois de importar CSV com ids explícitos: acerta as sequências (rodar no SQL Editor)
--   select estoque.ajustar_sequencias();
create function estoque.ajustar_sequencias()
returns text
language sql
set search_path = ''
as $$
  select concat_ws(', ',
    'movimentacoes ' || setval(pg_get_serial_sequence('estoque.movimentacoes', 'id'),
                               greatest((select max(id) from estoque.movimentacoes), 1)),
    'machinecards '  || setval(pg_get_serial_sequence('estoque.machinecards', 'id'),
                               greatest((select max(id) from estoque.machinecards), 1)),
    'ajustes '       || setval(pg_get_serial_sequence('estoque.ajustes', 'id'),
                               greatest((select max(id) from estoque.ajustes), 1)));
$$;
revoke all on function estoque.ajustar_sequencias() from public, anon, authenticated;
